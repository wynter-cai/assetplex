/**
 * Claude Code 适配器
 *
 * 配置目录：~/.claude/（支持 CLAUDE_CONFIG_DIR 环境变量重定向）
 * 全局 MCP：~/.claude.json（在 home 根，不在 .claude 内）
 * 标志文件：CLAUDE.md、settings.json
 *
 * 核心优势：Claude Code 原生支持 @path 导入语法，最大 5 层递归
 * AssetPlex 利用此机制，生成 ~/.claude/CLAUDE.md 聚合所有 Hub 内容的 @import
 */

import { BaseAdapter } from './base.js';
import type { HubItem, SyncTarget, DiscoveredItem } from '../types.js';
import type { HubConfig } from '../config.js';
import type { ToolConfig } from './types.js';
import { existsSync, writeFileSync, readFileSync } from 'node:fs';
import { resolve, basename } from 'node:path';
import { homedir } from 'node:os';
import { hubPath } from '../../utils/paths.js';
import { listMarkdownFilesRecursive } from '../../utils/fs.js';

/**
 * CLAUDE.md 聚合内容中要 @import 的固定 Hub 文件列表
 *
 * rules/ 目录不在这里硬编码，而是在 applyNativeImport 时动态扫描，
 * 确保用户新增的规则文件无需改代码就能被 Claude Code 加载。
 */
const CLAUDE_MD_FIXED_IMPORTS = [
  'identity/profile.md',
  'identity/profile.auto.md',
  'identity/communication-style.md',
  'identity/tech-stack.md',
  'identity/env.md',
  'preferences/coding-style.md',
  'preferences/git-workflow.md',
];

/**
 * 动态构造完整的 @import 列表：固定文件 + rules/ 下所有 .md
 */
function buildImportList(): string[] {
  const rulesImports = listMarkdownFilesRecursive(hubPath('rules')).map(
    (rel) => `rules/${rel}`,
  );
  return [...CLAUDE_MD_FIXED_IMPORTS, ...rulesImports];
}

/** CLAUDE.md 自动生成头部 */
const CLAUDE_MD_HEADER =
  '<!-- AUTO-GENERATED by assetplex. Do not edit directly. Run `assetplex sync` to update. -->\n';

export class ClaudeCodeAdapter extends BaseAdapter {
  readonly name = 'claude-code';
  readonly displayName = 'Claude Code';
  readonly homepage = 'https://code.claude.com/docs';

  protected defaultConfigDir = '~/.claude';
  protected signatureFiles = ['settings.json'];
  protected supportedTargets = [
    'CLAUDE.md',
    'skills/',
    'rules/',
    'commands/',
    'agents/',
  ];

  /**
   * 重写 detect：
   * - 检查 ~/.claude/ 是否存在
   * - 支持 CLAUDE_CONFIG_DIR 环境变量重定向
   * - 检查 ~/.claude.json 是否存在（全局 MCP）
   */
  async detect() {
    const configDir = this.getConfigDir();
    const settingsPath = resolve(configDir, 'settings.json');
    const claudeMdPath = resolve(configDir, 'CLAUDE.md');

    const configDirExists = existsSync(configDir);
    const hasSettings = existsSync(settingsPath);
    const hasClaudeMd = existsSync(claudeMdPath);

    // 安装判断：目录存在且任一标志文件存在
    const installed = configDirExists && (hasSettings || hasClaudeMd);

    // 尝试获取 Claude Code CLI 版本
    let version: string | undefined;
    try {
      const { execSync } = await import('node:child_process');
      const output = execSync('claude --version 2>&1', {
        encoding: 'utf-8',
        timeout: 3000,
        stdio: ['pipe', 'pipe', 'pipe'],
      }).trim();
      const match = output.match(/(\d+\.\d+\.\d+)/);
      if (match) version = match[1];
    } catch {
      // CLI 未安装或不在 PATH
    }

    return {
      name: this.name,
      installed,
      configDirExists,
      version,
      configDir,
      error: installed
        ? undefined
        : configDirExists
          ? '缺少标志性文件 settings.json'
          : '未安装 Claude Code CLI',
    };
  }

  /**
   * 获取配置目录（支持 CLAUDE_CONFIG_DIR 环境变量）
   */
  override getConfigDir(): string {
    const fromEnv = process.env.CLAUDE_CONFIG_DIR;
    if (fromEnv) return this.expandHome(fromEnv);
    return this.expandHome(this.defaultConfigDir);
  }

  /**
   * 重写 resolveHubItems：明确关联 Hub 内文件与 Claude Code 目标
   *
   * 关联关系：
   * - Hub: identity/* + preferences/* + rules/* → Claude: CLAUDE.md (native-import)
   * - Hub: skills/                                  → Claude: skills         (symlink, dir)
   * - Hub: rules/                                   → Claude: rules           (symlink, dir)
   * - Hub: commands/                                → Claude: commands        (symlink, dir)
   * - Hub: agents/                                  → Claude: agents          (symlink, dir)
   * - Hub: mcp/mcp.sources.json                     → Claude: ~/.claude.json  (copy)
   */
  override resolveHubItems(_hubConfig: HubConfig, _hubRoot: string): Array<{ item: HubItem; target: SyncTarget }> {
    const base = this.getConfigDir();
    const home = homedir();

    // CLAUDE.md 用一个虚拟 HubItem 代表（applyNativeImport 会读取多个 Hub 文件聚合生成）
    const claudeMdItem: HubItem = {
      type: 'identity',
      relativePath: 'CLAUDE.md',  // 虚拟路径，仅用于标识
      absolutePath: hubPath('identity/profile.md'),  // 第一个被 import 的文件作为锚点
    };

    return [
      {
        item: claudeMdItem,
        target: {
          tool: this.name,
          targetPath: resolve(base, 'CLAUDE.md'),
          strategy: 'native-import',
          isDirectory: false,
        },
      },
      {
        item: {
          type: 'skill',
          relativePath: 'skills',
          absolutePath: hubPath('skills'),
        },
        target: {
          tool: this.name,
          targetPath: resolve(base, 'skills'),
          strategy: 'symlink',
          isDirectory: true,
        },
      },
      {
        item: {
          type: 'rule',
          relativePath: 'rules',
          absolutePath: hubPath('rules'),
        },
        target: {
          tool: this.name,
          targetPath: resolve(base, 'rules'),
          strategy: 'symlink',
          isDirectory: true,
        },
      },
      {
        item: {
          type: 'command',
          relativePath: 'commands',
          absolutePath: hubPath('commands'),
        },
        target: {
          tool: this.name,
          targetPath: resolve(base, 'commands'),
          strategy: 'symlink',
          isDirectory: true,
        },
      },
      {
        item: {
          type: 'agent',
          relativePath: 'agents',
          absolutePath: hubPath('agents'),
        },
        target: {
          tool: this.name,
          targetPath: resolve(base, 'agents'),
          strategy: 'symlink',
          isDirectory: true,
        },
      },
      // 全局 MCP 配置（在 home 根，不在 .claude 内）
      {
        item: {
          type: 'mcp',
          relativePath: 'mcp/mcp.sources.json',
          absolutePath: hubPath('mcp/mcp.sources.json'),
        },
        target: {
          tool: this.name,
          targetPath: resolve(home, '.claude.json'),
          strategy: 'copy',
          isDirectory: false,
        },
      },
    ];
  }

  /**
   * 同步目标列表（向后兼容）
   * 注意：CLAUDE.md 用 native-import 策略，其余用 symlink
   */
  targets(config: ToolConfig): SyncTarget[] {
    const configDir = config.configDir || this.defaultConfigDir;
    const base = this.expandHome(configDir);

    return [
      {
        tool: this.name,
        targetPath: resolve(base, 'CLAUDE.md'),
        strategy: 'native-import',
        isDirectory: false,
      },
      {
        tool: this.name,
        targetPath: resolve(base, 'skills'),
        strategy: 'symlink',
        isDirectory: true,
      },
      {
        tool: this.name,
        targetPath: resolve(base, 'rules'),
        strategy: 'symlink',
        isDirectory: true,
      },
      {
        tool: this.name,
        targetPath: resolve(base, 'commands'),
        strategy: 'symlink',
        isDirectory: true,
      },
      {
        tool: this.name,
        targetPath: resolve(base, 'agents'),
        strategy: 'symlink',
        isDirectory: true,
      },
      {
        tool: this.name,
        targetPath: resolve(homedir(), '.claude.json'),
        strategy: 'copy',
        isDirectory: false,
      },
    ];
  }

  /**
   * 重写 applyNativeImport：生成 CLAUDE.md 聚合 @import
   *
   * 生成内容：
   *   <!-- AUTO-GENERATED by assetplex ... -->
   *   @~/.assetplex/identity/profile.md
   *   @~/.assetplex/identity/profile.auto.md
   *   ...
   */
  protected override async applyNativeImport(_item: HubItem, target: SyncTarget): Promise<void> {
    const lines = [CLAUDE_MD_HEADER, ''];
    for (const relPath of buildImportList()) {
      const absPath = hubPath(relPath);
      if (existsSync(absPath)) {
        lines.push(`@${absPath.replace(/\\/g, '/')}`);
      }
    }
    lines.push('');

    writeFileSync(target.targetPath, lines.join('\n'), 'utf-8');
  }

  /**
   * 重写 apply：处理 .claude.json 的特殊逻辑（直接复制，不转换格式）
   */
  override async apply(item: HubItem, target: SyncTarget): Promise<void> {
    // .claude.json 是 JSON 格式，Hub 的 mcp.sources.json 也是 JSON，直接 copy
    if (target.targetPath.endsWith('.claude.json')) {
      const content = readFileSync(item.absolutePath);
      writeFileSync(target.targetPath, content, 'utf-8');
      return;
    }
    // 其他情况走默认实现
    return super.apply(item, target);
  }

  /**
   * 反向导入：从 Claude Code 读 CLAUDE.md 到 Hub
   *
   * 注意：CLAUDE.md 是自动生成的，反向导入意义不大；
   * 但 .claude.json 反向导入可恢复 MCP 配置
   */
  override async import(targetPath: string): Promise<HubItem> {
    const content = readFileSync(targetPath);

    let type: HubItem['type'] = 'preference';
    if (targetPath.endsWith('CLAUDE.md')) type = 'identity';
    else if (targetPath.endsWith('.claude.json')) type = 'mcp';
    else if (targetPath.includes('skills')) type = 'skill';
    else if (targetPath.includes('rules')) type = 'rule';
    else if (targetPath.includes('commands')) type = 'command';
    else if (targetPath.includes('agents')) type = 'agent';

    return {
      type,
      relativePath: basename(targetPath),
      absolutePath: targetPath,
      content,
    };
  }

  /**
   * 扫描 Claude Code 目录，发现所有可导入内容
   */
  override async scan(): Promise<DiscoveredItem[]> {
    const base = this.getConfigDir();
    const home = homedir();
    const items: DiscoveredItem[] = [];

    // CLAUDE.md → identity/profile.md（如果不是 AUTO-GENERATED 的）
    const claudeMdPath = resolve(base, 'CLAUDE.md');
    if (existsSync(claudeMdPath)) {
      try {
        const content = readFileSync(claudeMdPath, 'utf-8');
        if (!content.includes('AUTO-GENERATED by assetplex')) {
          const item = this.makeDiscoveredItem(claudeMdPath, base, 'identity/claude-code.md', 'identity');
          if (item) items.push(item);
        }
      } catch {
        // 忽略
      }
    }

    // skills/ 目录
    items.push(...this.scanDirectory(resolve(base, 'skills'), base, 'skills', 'skill'));

    // rules/ 目录
    items.push(...this.scanDirectory(resolve(base, 'rules'), base, 'rules', 'rule'));

    // commands/ 目录 → commands/（preference 类别）
    items.push(...this.scanDirectory(resolve(base, 'commands'), base, 'commands', 'preference'));

    // agents/ 目录 → agents/（preference 类别）
    items.push(...this.scanDirectory(resolve(base, 'agents'), base, 'agents', 'preference'));

    // ~/.claude.json → mcp/mcp.sources.json
    const claudeJsonPath = resolve(home, '.claude.json');
    const claudeJsonItem = this.makeDiscoveredItem(claudeJsonPath, home, 'mcp/mcp.sources.json', 'mcp');
    if (claudeJsonItem) items.push(claudeJsonItem);

    return items;
  }
}
